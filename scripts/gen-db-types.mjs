// Generates packages/db/src/database.types.ts from local Supabase.
//
// Both `pnpm db:types` and CI call this, so the file they produce is byte for
// byte the same and the staleness check in CI means something.

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const HEADER = '// Generated by pnpm db:types. Do not edit by hand.\n';
const OUT = 'packages/db/src/database.types.ts';

let generated;
try {
  generated = execFileSync('supabase', ['gen', 'types', 'typescript', '--local'], {
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
    stdio: ['ignore', 'pipe', 'inherit'],
    shell: process.platform === 'win32',
  });
} catch {
  console.error(
    'Could not reach local Supabase.\n' +
      'Start Docker, run pnpm db:start, then try again.\n' +
      'CI generates these types on every pull request if you cannot run them here.',
  );
  process.exit(1);
}

writeFileSync(OUT, HEADER + generated);
console.log(`Wrote ${OUT}, ${generated.split('\n').length} lines.`);
